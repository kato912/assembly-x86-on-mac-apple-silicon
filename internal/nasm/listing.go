package nasm

import (
	"bufio"
	"io"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// Loc is a position in the user's source code.
type Loc struct {
	Line  int    // line number (in File, or in the main file when File == "")
	Text  string // source text of that line, trimmed
	File  string // include file name, "" for the main source file
	Macro string // for code generated by a macro: the expanded line's text
}

// SecOff is an offset inside a named section.
type SecOff struct {
	Section string
	Off     uint64
}

type entry struct {
	off uint64
	loc Loc
}

// LineMap maps section offsets to source lines, built from a nasm listing.
type LineMap struct {
	sections map[string][]entry // sorted by off
	lines    map[int][]SecOff   // main-file line -> code/data emitted for it
	texts    map[int]string     // main-file line -> text
}

var (
	sectionRE  = regexp.MustCompile(`(?i)^\[?\s*(?:section|segment)\s+([^\s\]]+)`)
	absoluteRE = regexp.MustCompile(`(?i)^\[?\s*absolute\b`)
	strucRE    = regexp.MustCompile(`(?i)^(?:\S+:?\s+)?struc\b`)
	endstrucRE = regexp.MustCompile(`(?i)^endstruc\b`)
	macroRE    = regexp.MustCompile(`(?i)^%i?macro\b`)
	endmacroRE = regexp.MustCompile(`(?i)^%endm(?:acro)?\b`)
	includeRE  = regexp.MustCompile(`(?i)^%include\s+["'<]?([^"'>]+)`)
	endrepRE   = regexp.MustCompile(`(?i)^%endrep\b`)
	sectRE     = regexp.MustCompile(`__SECT__`)
)

type ctxKind uint8

const (
	ctxFile ctxKind = iota
	ctxMacro
	ctxRep
)

type ctx struct {
	kind ctxKind
	file string
	line int
	text string
}

// ParseListing reads a nasm -l listing.
func ParseListing(r io.Reader) (*LineMap, error) {
	lm := &LineMap{sections: map[string][]entry{}, lines: map[int][]SecOff{}, texts: map[int]string{}}
	stack := []ctx{{kind: ctxFile}}
	section, userSection := ".text", ".text"
	macroDef := 0
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		num, off, hasOff, data, level, text, ok := parseListingLine(sc.Text())
		if !ok {
			continue
		}
		// Adjust the context stack to this line's nesting level.
		if level+1 < len(stack) {
			stack = stack[:level+1]
		}
		for len(stack) < level+1 {
			parent := stack[len(stack)-1]
			child := ctx{kind: ctxMacro, file: parent.file, line: parent.line, text: parent.text}
			if m := includeRE.FindStringSubmatch(parent.text); m != nil {
				child = ctx{kind: ctxFile, file: strings.TrimSpace(m[1])}
			} else if endrepRE.MatchString(parent.text) {
				child = ctx{kind: ctxRep, file: parent.file}
			}
			stack = append(stack, child)
		}
		cur := &stack[level]
		if text != "" {
			switch cur.kind {
			case ctxFile, ctxRep:
				cur.line, cur.text = num, text
			case ctxMacro:
				cur.text = text // keep the invocation's line number
			}
			if level == 0 {
				lm.texts[num] = text
			}
			// Track the current section (ignoring macro definitions).
			switch {
			case macroRE.MatchString(text):
				macroDef++
			case endmacroRE.MatchString(text):
				if macroDef > 0 {
					macroDef--
				}
			case macroDef > 0:
			case sectionRE.MatchString(text):
				section = sectionRE.FindStringSubmatch(text)[1]
				if cur.kind != ctxMacro {
					userSection = section
				}
			case absoluteRE.MatchString(text), strucRE.MatchString(text):
				section = ""
			case endstrucRE.MatchString(text), sectRE.MatchString(text):
				section = userSection
			}
		}
		if !hasOff || data == "" || section == "" || strings.Trim(data, "?") == "" {
			continue
		}
		loc := locate(stack)
		lm.add(section, off, loc)
	}
	for s := range lm.sections {
		es := lm.sections[s]
		sort.SliceStable(es, func(i, j int) bool { return es[i].off < es[j].off })
	}
	return lm, sc.Err()
}

func locate(stack []ctx) Loc {
	i := len(stack) - 1
	var macroText string
	if stack[i].kind == ctxMacro {
		macroText = stack[i].text
	}
	for i > 0 && stack[i].kind == ctxMacro {
		i--
	}
	c := stack[i]
	return Loc{Line: c.line, Text: c.text, File: c.file, Macro: macroText}
}

func (lm *LineMap) add(section string, off uint64, loc Loc) {
	es := lm.sections[section]
	// Keep the first entry for an offset (continuation lines repeat it).
	for i := len(es) - 1; i >= 0 && i >= len(es)-4; i-- {
		if es[i].off == off {
			return
		}
	}
	lm.sections[section] = append(es, entry{off, loc})
	if loc.File == "" {
		lm.lines[loc.Line] = append(lm.lines[loc.Line], SecOff{section, off})
	}
}

// Lookup returns the source location for an offset in a section: the line
// that emitted it, or the closest preceding one.
func (lm *LineMap) Lookup(section string, off uint64) (Loc, bool) {
	if lm == nil {
		return Loc{}, false
	}
	es := lm.sections[section]
	i := sort.Search(len(es), func(i int) bool { return es[i].off > off })
	if i == 0 {
		return Loc{}, false
	}
	return es[i-1].loc, true
}

// Places returns where code/data for a main-file line was emitted.
func (lm *LineMap) Places(line int) []SecOff {
	if lm == nil {
		return nil
	}
	return lm.lines[line]
}

// Lines returns the sorted main-file line numbers that emitted something.
func (lm *LineMap) Lines() []int {
	var out []int
	for l := range lm.lines {
		out = append(out, l)
	}
	sort.Ints(out)
	return out
}

// Text returns the text of a main-file line as shown in the listing.
func (lm *LineMap) Text(line int) string {
	if lm == nil {
		return ""
	}
	return lm.texts[line]
}

var levelRE = regexp.MustCompile(`^\s*<(\d+)>(.*)$`)

// parseListingLine splits one listing line. The layout (nasm's
// list_emit) is: line number (6), space, offset (8 hex), space, data
// (18, may contain "<res 4h>"), nesting marker "<n>", source text.
func parseListingLine(s string) (num int, off uint64, hasOff bool, data string, level int, text string, ok bool) {
	s = strings.TrimRight(s, "\r")
	if len(s) < 7 {
		return
	}
	n, err := strconv.Atoi(strings.TrimSpace(s[:6]))
	if err != nil {
		return
	}
	num, ok = n, true
	rest := s[7:]
	if len(rest) >= 9 && isHex(rest[:8]) && rest[8] == ' ' {
		off, _ = strconv.ParseUint(rest[:8], 16, 64)
		hasOff = true
		d := rest[9:]
		end := 18
		if len(d) < end {
			end = len(d)
		}
		// The data column overflows its 18 characters only rarely; then it
		// ends at the first double space.
		if len(d) > 18 && d[18] != ' ' {
			if k := strings.Index(d[18:], "  "); k >= 0 {
				end = 18 + k
			} else {
				end = len(d)
			}
		}
		data = strings.TrimSpace(d[:end])
		rest = d[end:]
	} else if len(rest) > 27 {
		rest = rest[27:]
	} else {
		rest = ""
	}
	if m := levelRE.FindStringSubmatch(rest); m != nil {
		level, _ = strconv.Atoi(m[1])
		rest = m[2]
	}
	text = strings.TrimSpace(rest)
	return
}

func isHex(s string) bool {
	for i := 0; i < len(s); i++ {
		c := s[i]
		if !(c >= '0' && c <= '9' || c >= 'A' && c <= 'F' || c >= 'a' && c <= 'f') {
			return false
		}
	}
	return true
}
