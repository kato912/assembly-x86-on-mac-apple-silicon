package emu

import (
	"fmt"
	"sort"
)

// PageSize is the size of one emulated memory page.
const PageSize = 4096

// Perm is a set of memory access permissions.
type Perm uint8

const (
	PermR Perm = 1 << iota
	PermW
	PermX
)

func (p Perm) String() string {
	s := []byte("---")
	if p&PermR != 0 {
		s[0] = 'r'
	}
	if p&PermW != 0 {
		s[1] = 'w'
	}
	if p&PermX != 0 {
		s[2] = 'x'
	}
	return string(s)
}

// Access is the kind of memory access being made.
type Access uint8

const (
	AccessRead Access = iota
	AccessWrite
	AccessExec
)

func (a Access) need() Perm {
	switch a {
	case AccessWrite:
		return PermW
	case AccessExec:
		return PermX
	}
	return PermR
}

// RegionKind classifies a mapped region so error messages can explain it.
type RegionKind uint8

const (
	KindSection RegionKind = iota // a section of the program (.text, .data, ...)
	KindStack
	KindStackGuard // unmapped area just below the stack: touching it = stack overflow
	KindHeap       // memory obtained with brk
	KindStub       // helper code generated by nasmx86 itself
)

// Region is a contiguous, page-aligned range of mapped addresses.
type Region struct {
	Start, End uint64 // [Start, End)
	Perm       Perm
	Name       string
	Kind       RegionKind
}

func (r *Region) contains(a uint64) bool { return a >= r.Start && a < r.End }

// MemFault describes an invalid memory access.
type MemFault struct {
	Addr   uint64
	Access Access
	Region *Region // region containing Addr, nil when Addr is not mapped at all
}

func (f *MemFault) Error() string {
	verb := map[Access]string{AccessRead: "read", AccessWrite: "write", AccessExec: "execute"}[f.Access]
	if f.Region != nil {
		return fmt.Sprintf("cannot %s memory at %#x (%s is %s)", verb, f.Addr, f.Region.Name, f.Region.Perm)
	}
	return fmt.Sprintf("cannot %s memory at %#x (not mapped)", verb, f.Addr)
}

type page struct {
	data [PageSize]byte
	perm Perm
}

// Memory is a sparse, paged address space. Pages are allocated lazily the
// first time an address inside a mapped region is touched.
type Memory struct {
	pages   map[uint64]*page
	regions []*Region // sorted by Start, non-overlapping

	lastIdx uint64
	last    *page

	// OnWrite, when non-nil, is called after every successful program write
	// (used by --trace to show memory changes).
	OnWrite func(addr uint64, size int, val uint64)
}

// NewMemory returns an empty address space.
func NewMemory() *Memory {
	return &Memory{pages: make(map[uint64]*page), lastIdx: ^uint64(0)}
}

// Map adds a region. start and size are rounded out to page boundaries.
func (m *Memory) Map(start, size uint64, perm Perm, name string, kind RegionKind) *Region {
	s := start &^ (PageSize - 1)
	e := (start + size + PageSize - 1) &^ (PageSize - 1)
	r := &Region{Start: s, End: e, Perm: perm, Name: name, Kind: kind}
	m.regions = append(m.regions, r)
	sort.Slice(m.regions, func(i, j int) bool { return m.regions[i].Start < m.regions[j].Start })
	// Pages already allocated in this range take the new permissions.
	for a := s; a < e; a += PageSize {
		if p := m.pages[a/PageSize]; p != nil {
			p.perm = perm
		}
	}
	return r
}

// Regions returns the mapped regions in address order.
func (m *Memory) Regions() []*Region { return m.regions }

// FindRegion returns the region containing addr, or nil.
func (m *Memory) FindRegion(addr uint64) *Region {
	i := sort.Search(len(m.regions), func(i int) bool { return m.regions[i].End > addr })
	if i < len(m.regions) && m.regions[i].contains(addr) {
		return m.regions[i]
	}
	return nil
}

// Grow extends region r so that it ends at newEnd (page aligned up).
func (m *Memory) Grow(r *Region, newEnd uint64) {
	r.End = (newEnd + PageSize - 1) &^ (PageSize - 1)
}

func (m *Memory) page(addr uint64, acc Access, force bool) (*page, error) {
	idx := addr / PageSize
	var p *page
	if idx == m.lastIdx {
		p = m.last
	} else {
		p = m.pages[idx]
		if p == nil {
			r := m.FindRegion(addr)
			if r == nil || (r.Perm == 0 && !force) {
				return nil, &MemFault{Addr: addr, Access: acc, Region: r}
			}
			p = &page{perm: r.Perm}
			m.pages[idx] = p
		}
		m.lastIdx, m.last = idx, p
	}
	if !force && p.perm&acc.need() == 0 {
		return nil, &MemFault{Addr: addr, Access: acc, Region: m.FindRegion(addr)}
	}
	return p, nil
}

// Check reports whether the n bytes at addr can be accessed with acc,
// returning the fault for the first bad byte.
func (m *Memory) Check(addr uint64, n int, acc Access) error {
	end := addr + uint64(n)
	for a := addr; a < end; a = (a/PageSize + 1) * PageSize {
		if _, err := m.page(a, acc, false); err != nil {
			return err
		}
		if (a/PageSize+1)*PageSize == 0 { // wrapped
			break
		}
	}
	return nil
}

// Read reads a little-endian value of size bytes (1, 2, 4 or 8).
func (m *Memory) Read(addr uint64, size int) (uint64, error) {
	off := addr % PageSize
	if off+uint64(size) <= PageSize {
		p, err := m.page(addr, AccessRead, false)
		if err != nil {
			return 0, err
		}
		d := p.data[off:]
		switch size {
		case 1:
			return uint64(d[0]), nil
		case 2:
			return uint64(d[0]) | uint64(d[1])<<8, nil
		case 4:
			return uint64(d[0]) | uint64(d[1])<<8 | uint64(d[2])<<16 | uint64(d[3])<<24, nil
		}
		var v uint64
		for i := size - 1; i >= 0; i-- {
			v = v<<8 | uint64(d[i])
		}
		return v, nil
	}
	// Crosses a page boundary.
	if err := m.Check(addr, size, AccessRead); err != nil {
		return 0, err
	}
	var v uint64
	for i := size - 1; i >= 0; i-- {
		p, _ := m.page(addr+uint64(i), AccessRead, false)
		v = v<<8 | uint64(p.data[(addr+uint64(i))%PageSize])
	}
	return v, nil
}

// Write writes a little-endian value of size bytes.
func (m *Memory) Write(addr uint64, size int, val uint64) error {
	if err := m.Check(addr, size, AccessWrite); err != nil {
		return err
	}
	m.store(addr, size, val)
	if m.OnWrite != nil {
		m.OnWrite(addr, size, val)
	}
	return nil
}

func (m *Memory) store(addr uint64, size int, val uint64) {
	off := addr % PageSize
	if off+uint64(size) <= PageSize {
		p, _ := m.page(addr, AccessRead, true)
		for i := 0; i < size; i++ {
			p.data[off+uint64(i)] = byte(val >> (8 * i))
		}
		return
	}
	for i := 0; i < size; i++ {
		a := addr + uint64(i)
		p, _ := m.page(a, AccessRead, true)
		p.data[a%PageSize] = byte(val >> (8 * i))
	}
}

// ReadBytes copies n bytes starting at addr.
func (m *Memory) ReadBytes(addr uint64, n int) ([]byte, error) {
	if err := m.Check(addr, n, AccessRead); err != nil {
		return nil, err
	}
	return m.copyOut(addr, n), nil
}

// Peek copies up to n readable bytes at addr without faulting (for debuggers).
func (m *Memory) Peek(addr uint64, n int) []byte {
	out := make([]byte, 0, n)
	for i := 0; i < n; i++ {
		a := addr + uint64(i)
		r := m.FindRegion(a)
		if r == nil || r.Perm&PermR == 0 {
			break
		}
		p, _ := m.page(a, AccessRead, true)
		out = append(out, p.data[a%PageSize])
	}
	return out
}

func (m *Memory) copyOut(addr uint64, n int) []byte {
	out := make([]byte, n)
	for i := 0; i < n; {
		a := addr + uint64(i)
		p, _ := m.page(a, AccessRead, true)
		off := a % PageSize
		c := copy(out[i:], p.data[off:])
		i += c
	}
	return out
}

// WriteBytes copies b to addr, checking write permission.
func (m *Memory) WriteBytes(addr uint64, b []byte) error {
	if err := m.Check(addr, len(b), AccessWrite); err != nil {
		return err
	}
	m.Poke(addr, b)
	return nil
}

// Poke copies b to addr ignoring permissions (used by the loader). The
// addresses must lie inside mapped regions.
func (m *Memory) Poke(addr uint64, b []byte) {
	for i := 0; i < len(b); {
		a := addr + uint64(i)
		p, err := m.page(a, AccessRead, true)
		if err != nil {
			panic(fmt.Sprintf("Poke outside mapped memory at %#x", a))
		}
		off := a % PageSize
		i += copy(p.data[off:], b[i:])
	}
}

// Fetch copies up to len(buf) executable bytes at addr into buf. It fails if
// the first byte is not executable and otherwise stops at the first
// non-executable byte.
func (m *Memory) Fetch(addr uint64, buf []byte) (int, error) {
	n := 0
	for n < len(buf) {
		a := addr + uint64(n)
		p, err := m.page(a, AccessExec, false)
		if err != nil {
			if n == 0 {
				return 0, err
			}
			break
		}
		off := a % PageSize
		n += copy(buf[n:], p.data[off:])
	}
	return n, nil
}
